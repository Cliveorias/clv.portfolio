-- ---------- PROJECTS ----------
create table if not exists projects (
  id           bigint generated by default as identity primary key,
  title        text not null,
  description  text,
  tags         text[] default '{}',
  project_url  text,
  repo_url     text,
  image_url    text,
  sort_order   int default 0,
  created_at   timestamptz default now()
);
alter table projects enable row level security;

create policy "Public can read projects"
  on projects for select using (true);

create policy "Only authenticated users can modify projects"
  on projects for all
  using (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');

-- ---------- MESSAGES (contact form) ----------
create table if not exists messages (
  id           bigint generated by default as identity primary key,
  name         text not null,
  email        text not null,
  message      text not null,
  created_at   timestamptz default now()
);
alter table messages enable row level security;

create policy "Public can submit messages"
  on messages for insert with check (true);

create policy "Only authenticated users can read messages"
  on messages for select using (auth.role() = 'authenticated');

-- ---------- SCORES (Tetris leaderboard) ----------
create table if not exists scores (
  id           bigint generated by default as identity primary key,
  player_name  text not null unique,
  score        int not null,
  created_at   timestamptz default now()
);
alter table scores enable row level security;

create policy "Public can read scores"
  on scores for select using (true);

create policy "Public can submit scores"
  on scores for insert
  with check (
    char_length(player_name) between 1 and 20
    and score >= 0 and score <= 999999
  );

create policy "Public can update scores"
  on scores for update
  using (true)
  with check (
    char_length(player_name) between 1 and 20
    and score >= 0 and score <= 999999
  );
